import { Document, Page, Text, View, StyleSheet, renderToBuffer } from '@react-pdf/renderer';
import { readableTextOn } from '@/lib/domain/text';

export type ReportPdfData = {
  companyName: string;
  monthLabel: string;
  brandColor: string;
  summary: string;
  kpis: { metric: string; target: number; actual: number }[];
  spend: { budget: string; spent: string };
  adverts: { title: string; format: string; hook: string; audience: string; spend: string; results: string; learnings: string }[];
  logos: { name: string; rationale: string; selected: boolean }[];
  research: string;
  recommendations: string;
};

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 10, fontFamily: 'Helvetica', color: '#111827', lineHeight: 1.45 },
  h1: { fontSize: 22, fontFamily: 'Helvetica-Bold' },
  h2: { fontSize: 13, fontFamily: 'Helvetica-Bold', marginTop: 18, marginBottom: 6 },
  muted: { color: '#6B7280' },
  row: { flexDirection: 'row', borderBottom: '1 solid #E5E7EB', paddingVertical: 4 },
  cell: { flex: 1 },
  card: { border: '1 solid #E5E7EB', borderRadius: 4, padding: 8, marginBottom: 8 },
  bold: { fontFamily: 'Helvetica-Bold' },
});

function ReportPdf({ d }: { d: ReportPdfData }) {
  const band = { backgroundColor: d.brandColor, color: readableTextOn(d.brandColor), padding: 24, marginHorizontal: -40, marginTop: -40, marginBottom: 16 };
  return (
    <Document title={`${d.companyName} — ${d.monthLabel} TikTok report`}>
      <Page size="A4" style={styles.page}>
        <View style={band}>
          <Text style={styles.h1}>{d.companyName}</Text>
          <Text>TikTok marketing report · {d.monthLabel}</Text>
        </View>
        <Text style={styles.h2}>Summary</Text>
        <Text>{d.summary}</Text>
        <Text style={styles.h2}>KPIs</Text>
        <View style={[styles.row, styles.bold]}>
          <Text style={styles.cell}>Metric</Text>
          <Text style={styles.cell}>Target</Text>
          <Text style={styles.cell}>Actual</Text>
          <Text style={styles.cell}>Status</Text>
        </View>
        {d.kpis.map((k) => (
          <View style={styles.row} key={k.metric}>
            <Text style={styles.cell}>{k.metric}</Text>
            <Text style={styles.cell}>{k.target}</Text>
            <Text style={styles.cell}>{k.actual}</Text>
            <Text style={styles.cell}>{k.actual >= k.target ? 'Met' : 'Below target'}</Text>
          </View>
        ))}
        <Text style={{ marginTop: 6 }}>
          Ad budget {d.spend.budget} · spent {d.spend.spent}
        </Text>
        <Text style={styles.h2}>Adverts and posts</Text>
        {d.adverts.map((a, i) => (
          <View style={styles.card} key={i} wrap={false}>
            <Text style={styles.bold}>
              {a.title} <Text style={styles.muted}>({a.format})</Text>
            </Text>
            <Text>Hook: {a.hook}</Text>
            <Text>Audience: {a.audience}</Text>
            <Text>Spend: {a.spend} · Results: {a.results}</Text>
            <Text style={styles.muted}>Learnings: {a.learnings}</Text>
          </View>
        ))}
        {d.logos.length > 0 && <Text style={styles.h2}>Logo design</Text>}
        {d.logos.map((l, i) => (
          <Text key={i}>
            • {l.name}
            {l.selected ? ' (selected)' : ''}: {l.rationale}
          </Text>
        ))}
        <Text style={styles.h2}>Market research recap</Text>
        <Text>{d.research}</Text>
        <Text style={styles.h2}>Recommendations for next month</Text>
        <Text>{d.recommendations}</Text>
        <Text style={[styles.muted, { position: 'absolute', bottom: 20, left: 40, fontSize: 8 }]} fixed>
          Generated by Marketing Agent
        </Text>
      </Page>
    </Document>
  );
}

export function renderReportPdf(d: ReportPdfData): Promise<Buffer> {
  return renderToBuffer(<ReportPdf d={d} />);
}
